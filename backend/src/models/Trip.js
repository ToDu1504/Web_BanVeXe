const { DataTypes } = require('sequelize')
const { sequelize } = require('../config/db')

const Trip = sequelize.define('Trip', {
  id: {
    type: DataTypes.INTEGER,
    autoIncrement: true,
    primaryKey: true,
  },
  route_id: {
    type: DataTypes.INTEGER,
    allowNull: false,
  },
  vehicle_id: {
    type: DataTypes.INTEGER,
    allowNull: false,
  },
  departure_time: {
    type: DataTypes.DATE,
    allowNull: false,
  },
  arrival_time: {
    type: DataTypes.DATE,
    allowNull: true,
  },
  available_seats: {
    type: DataTypes.INTEGER,
    allowNull: false,
  },
  price: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: false,
  },
  status: {
    type: DataTypes.ENUM('scheduled', 'ongoing', 'completed', 'cancelled'),
    defaultValue: 'scheduled',
  },
  // Set when this Trip was auto-generated by a TripTemplate (see
  // jobs/generateTripsFromTemplates.js). Deleting the template only clears
  // this (association onDelete: 'SET NULL') — it never touches the Trip.
  template_id: {
    type: DataTypes.INTEGER,
    allowNull: true,
  },
  // Tài xế được phân công (User.role = 'driver'). Xóa tài xế chỉ gỡ liên kết.
  driver_id: {
    type: DataTypes.INTEGER,
    allowNull: true,
  },
  // Tài xế phụ (lái thay ca trên cùng chuyến) — có hoặc không. Được xem chuyến,
  // điểm danh, báo sự cố; chỉ tài xế chính bấm Bắt đầu/Hoàn thành.
  co_driver_id: {
    type: DataTypes.INTEGER,
    allowNull: true,
  },
  // Cờ idempotent của job gửi mail nhắc chuyến (jobs/sendDepartureReminders.js).
  reminder_sent_at: {
    type: DataTypes.DATE,
    allowNull: true,
  },
  // Giờ chạy thực tế do tài xế bấm "Bắt đầu chạy"/"Hoàn thành" — khác
  // departure_time/arrival_time là giờ theo lịch.
  actual_departure_at: {
    type: DataTypes.DATE,
    allowNull: true,
  },
  actual_arrival_at: {
    type: DataTypes.DATE,
    allowNull: true,
  },
}, {
  tableName: 'trips',
  timestamps: true,
  indexes: [
    {
      fields: ['template_id', 'departure_time'],
      name: 'idx_trip_template_departure',
    },
    {
      fields: ['driver_id', 'departure_time'],
      name: 'idx_trips_driver',
    },
    {
      fields: ['co_driver_id', 'departure_time'],
      name: 'idx_trips_co_driver',
    },
  ],
})

module.exports = Trip
