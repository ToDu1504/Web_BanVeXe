const { DataTypes } = require('sequelize')
const { sequelize } = require('../config/db')

const Trip = sequelize.define('Trip', {
  id: {
    type: DataTypes.INTEGER,
    autoIncrement: true,
    primaryKey: true,
  },
  route_id: {
    type: DataTypes.INTEGER,
    allowNull: false,
  },
  vehicle_id: {
    type: DataTypes.INTEGER,
    allowNull: false,
  },
  departure_time: {
    type: DataTypes.DATE,
    allowNull: false,
  },
  arrival_time: {
    type: DataTypes.DATE,
    allowNull: true,
  },
  available_seats: {
    type: DataTypes.INTEGER,
    allowNull: false,
  },
  price: {
    type: DataTypes.DECIMAL(10, 2),
    allowNull: false,
  },
  status: {
    type: DataTypes.ENUM('scheduled', 'ongoing', 'completed', 'cancelled'),
    defaultValue: 'scheduled',
  },
  // Set when this Trip was auto-generated by a TripTemplate (see
  // jobs/generateTripsFromTemplates.js). Deleting the template only clears
  // this (association onDelete: 'SET NULL') — it never touches the Trip.
  template_id: {
    type: DataTypes.INTEGER,
    allowNull: true,
  },
}, {
  tableName: 'trips',
  timestamps: true,
  indexes: [
    {
      fields: ['template_id', 'departure_time'],
      name: 'idx_trip_template_departure',
    },
  ],
})

module.exports = Trip
